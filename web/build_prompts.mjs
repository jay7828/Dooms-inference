// Regenerates web/engine/prompts.ts from the Dooms backend's prompt files, byte for byte.
//   node web/build_prompts.mjs [path to src/dooms/llm/prompts]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const dir = process.argv[2] ?? path.join(here, '../src/dooms/llm/prompts')
const lit = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'
const files = {
  task_decomposer: 'task_decomposer.md',
  skill_generator: 'skill_generator.md',
  parameter_setter: 'parameter_setter.md',
  vision_grounder: 'vision_grounder.md',
}
const specs = { franka: 'robot_spec.md', so101: 'robot_spec_so101.md' }
const entries = (m) => Object.entries(m).map(([k, f]) => `  ${k}: ${lit(readFileSync(path.join(dir, f), 'utf8'))},`).join('\n')
const out = `/**
 * System prompts of the four agents and the per-arm spec text, copied byte for byte from the Dooms backend
 * (src/dooms/llm/prompts/*.md). Generated by web/build_prompts.mjs - do not edit by hand.
 * Loaded lazily with the Claude planner; the Demo planner never needs it.
 */
import { agentPrompts, robotSpecs } from './agents'

export const AGENT_PROMPTS = {
${entries(files)}
} as const

export const ROBOT_SPECS = {
${entries(specs)}
} as const

/** Fill the registries the agents read their system prompts from. */
export function registerPrompts(): void {
  Object.assign(agentPrompts, AGENT_PROMPTS)
  Object.assign(robotSpecs, ROBOT_SPECS)
}
`
writeFileSync(path.join(here, 'engine/prompts.ts'), out)
console.log('wrote web/engine/prompts.ts')
